import { existsSync, mkdirSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { basename, dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const API_ORIGIN = "https://api.guitar0.net";
const SOURCE_URL = `${API_ORIGIN}/api/v1/sync/lessons/`;
const OUTPUT_PATH = fileURLToPath(
  new URL("../assets/content/lessons.snapshot", import.meta.url),
);
const VERSION_PATH = fileURLToPath(
  new URL("../assets/content/lessons-snapshot-version.json", import.meta.url),
);
const SCHEMES_DIR = fileURLToPath(
  new URL("../assets/images/schemes/", import.meta.url),
);
const BUNDLED_SCHEMES_PATH = fileURLToPath(
  new URL("../src/features/lessons/bundled-schemes.ts", import.meta.url),
);
const DOWNLOAD_CONCURRENCY = 6;

function compare(a, b) {
  if (a < b) return -1;
  if (a > b) return 1;
  return 0;
}

function sortBy(items, ...keys) {
  return [...items].sort((a, b) => {
    for (const key of keys) {
      const result = compare(a[key], b[key]);
      if (result !== 0) return result;
    }
    return 0;
  });
}

function sortArrays(data) {
  return {
    ...data,
    lesson_uuids: [...data.lesson_uuids].sort(compare),
    course_uuids: [...data.course_uuids].sort(compare),
    lessons: sortBy(data.lessons, "uuid"),
    songs: sortBy(data.songs, "uuid"),
    courses: sortBy(data.courses, "uuid"),
    chords: sortBy(data.chords, "id"),
    schemes: sortBy(data.schemes, "id"),
    course_lessons: sortBy(data.course_lessons, "course_uuid", "order"),
  };
}

function schemeFiles(schemes) {
  const byName = new Map();
  for (const { image } of schemes) {
    const name = basename(image);
    const other = byName.get(name);
    if (other !== undefined && other !== image) {
      throw new Error(`${other} and ${image} share the file name ${name}`);
    }
    byName.set(name, image);
  }
  return byName;
}

async function downloadScheme(name, image) {
  const url = `${API_ORIGIN}${image}`;
  const response = await fetch(url);
  if (!response.ok) throw new Error(`${url} answered ${response.status}`);
  writeFileSync(join(SCHEMES_DIR, name), Buffer.from(await response.arrayBuffer()));
}

async function syncSchemeImages(files) {
  mkdirSync(SCHEMES_DIR, { recursive: true });
  const queue = [...files].filter(([name]) => !existsSync(join(SCHEMES_DIR, name)));
  const failures = [];
  const worker = async () => {
    for (let next = queue.shift(); next; next = queue.shift()) {
      const [name, image] = next;
      try {
        await downloadScheme(name, image);
      } catch (error) {
        failures.push(`${image}: ${error.message}`);
      }
    }
  };
  const downloads = queue.length;
  await Promise.all(Array.from({ length: DOWNLOAD_CONCURRENCY }, worker));
  if (failures.length > 0) {
    throw new Error(`Failed to download scheme images:\n${failures.join("\n")}`);
  }

  let removed = 0;
  for (const name of readdirSync(SCHEMES_DIR)) {
    if (files.has(name)) continue;
    rmSync(join(SCHEMES_DIR, name));
    removed += 1;
  }
  console.log(`Scheme images: ${downloads} downloaded, ${removed} removed`);
}

function writeBundledSchemes(files) {
  const entries = [...files]
    .sort(([, a], [, b]) => compare(a, b))
    .map(
      ([name, image]) =>
        `  ${JSON.stringify(image)}: require(${JSON.stringify(`@/assets/images/schemes/${name}`)}),`,
    );
  const source = [
    // REUSE-IgnoreStart
    "// SPDX-FileCopyrightText: 2026 Andrey Kotlyar <guitar0.app@gmail.com>",
    "//",
    "// SPDX-License-Identifier: AGPL-3.0-or-later",
    // REUSE-IgnoreEnd
    "",
    "// Generated by `npm run content:snapshot` from assets/content/lessons.snapshot.",
    "export const BUNDLED_SCHEME_IMAGES: Record<string, number> = {",
    ...entries,
    "};",
    "",
  ].join("\n");
  writeFileSync(BUNDLED_SCHEMES_PATH, source);
}

const response = await fetch(SOURCE_URL);
if (!response.ok) {
  throw new Error(`${SOURCE_URL} answered ${response.status}`);
}
const data = await response.json();
if (typeof data.version !== "string" || data.version === "") {
  throw new Error(`${SOURCE_URL} returned no version`);
}

mkdirSync(dirname(OUTPUT_PATH), { recursive: true });
writeFileSync(OUTPUT_PATH, `${JSON.stringify(sortArrays(data), null, 2)}\n`);
writeFileSync(VERSION_PATH, `${JSON.stringify({ version: data.version }, null, 2)}\n`);
console.log(`Content snapshot ${data.version} written to ${OUTPUT_PATH}`);

const files = schemeFiles(data.schemes);
await syncSchemeImages(files);
writeBundledSchemes(files);
console.log(`${files.size} scheme images listed in ${BUNDLED_SCHEMES_PATH}`);
